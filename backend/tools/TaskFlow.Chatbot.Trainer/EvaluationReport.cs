using System.Globalization;
using System.Text;
using TaskFlow.Application.Chatbot.KnowledgeBase;
using TaskFlow.Infrastructure.Chatbot;

/// <summary>Markdown calibration report for the intent model (accuracy, macro-F1, threshold/margin, confusions).</summary>
internal static class EvaluationReport
{
    public static string Build(IKnowledgeBase kb, IntentModelMetrics metrics)
    {
        var threshold = kb.Settings.ConfidenceThreshold;
        var margin = kb.Settings.MinMargin;
        var sb = new StringBuilder();
        var ci = CultureInfo.InvariantCulture;
        string P(double v) => (v * 100).ToString("0.0", ci) + "%";

        sb.AppendLine("# F13 intent classifier evaluation");
        sb.AppendLine();
        sb.AppendLine(ci, $"Generated by `TaskFlow.Chatbot.Trainer --report`. KB {kb.Settings.Version}, {metrics.Samples} utterances, {metrics.Folds}-fold stratified cross validation, seed {IntentModelTrainer.DefaultSeed}. Regenerate it after changing the KB.");
        sb.AppendLine();
        sb.AppendLine("## Accuracy");
        sb.AppendLine();
        sb.AppendLine("| Locale | Samples | Accuracy | Macro-F1 |");
        sb.AppendLine("|---|---|---|---|");
        foreach (var locale in metrics.PerLocaleAccuracy.Keys)
        {
            var rows = metrics.Predictions.Where(r => r.Locale == locale).ToList();
            sb.AppendLine(ci, $"| {locale} | {rows.Count} | {P(metrics.PerLocaleAccuracy[locale])} | {P(MacroF1(rows))} |");
        }

        sb.AppendLine(ci, $"| all | {metrics.Samples} | {P(metrics.Accuracy)} | {P(MacroF1(metrics.Predictions))} |");
        sb.AppendLine();
        sb.AppendLine(ci, $"## Answered vs fallback at threshold {threshold:0.00} and margin {margin:0.00}");
        sb.AppendLine();
        sb.AppendLine("A prediction is answered when the top score is at least the threshold and the gap to the second score is at least the margin; otherwise the bot falls back.");
        sb.AppendLine();
        sb.AppendLine("| Locale | Answered | Fallback | Accuracy of answered | Wrong answers (share of all) |");
        sb.AppendLine("|---|---|---|---|---|");
        foreach (var locale in metrics.PerLocaleAccuracy.Keys.Append("all"))
        {
            var rows = metrics.Predictions.Where(r => locale == "all" || r.Locale == locale).ToList();
            var answered = rows.Where(r => r.Score >= threshold && r.Margin >= margin).ToList();
            var correct = answered.Count(r => r.Intent == r.Predicted);
            var share = answered.Count / (double)rows.Count;
            var acc = answered.Count == 0 ? 0 : correct / (double)answered.Count;
            sb.AppendLine(ci, $"| {locale} | {P(share)} | {P(1 - share)} | {P(acc)} | {P((answered.Count - correct) / (double)rows.Count)} |");
        }

        sb.AppendLine();
        sb.AppendLine(ci, $"Threshold sweep (margin {margin:0.00}):");
        sb.AppendLine();
        sb.AppendLine("| Threshold | Answered | Accuracy of answered |");
        sb.AppendLine("|---|---|---|");
        foreach (var t in new[] { 0.40, 0.50, 0.55, 0.60, 0.65, 0.70, 0.75, 0.80 })
        {
            var answered = metrics.Predictions.Where(r => r.Score >= t && r.Margin >= margin).ToList();
            var acc = answered.Count == 0 ? 0 : answered.Count(r => r.Intent == r.Predicted) / (double)answered.Count;
            sb.AppendLine(ci, $"| {t:0.00} | {P(answered.Count / (double)metrics.Samples)} | {P(acc)} |");
        }

        sb.AppendLine();
        sb.AppendLine("## Per-intent recall");
        sb.AppendLine();
        sb.AppendLine("| Intent | Recall |");
        sb.AppendLine("|---|---|");
        foreach (var (intent, recall) in metrics.PerIntentRecall.OrderBy(e => e.Value).ThenBy(e => e.Key, StringComparer.Ordinal))
        {
            sb.AppendLine(ci, $"| {intent} | {P(recall)} |");
        }

        sb.AppendLine();
        sb.AppendLine("## Top confusion pairs (actual -> predicted)");
        sb.AppendLine();
        sb.AppendLine("| Actual | Predicted | Count | Example |");
        sb.AppendLine("|---|---|---|---|");
        var wrong = metrics.Predictions.Where(r => r.Intent != r.Predicted)
            .GroupBy(r => (r.Intent, r.Predicted))
            .OrderByDescending(g => g.Count()).ThenBy(g => g.Key.Intent, StringComparer.Ordinal).ThenBy(g => g.Key.Predicted, StringComparer.Ordinal)
            .Take(12);
        foreach (var g in wrong)
        {
            var example = g.OrderBy(r => r.Utterance, StringComparer.Ordinal).First().Utterance.Replace("|", "/", StringComparison.Ordinal);
            sb.AppendLine(ci, $"| {g.Key.Intent} | {g.Key.Predicted} | {g.Count()} | {example} |");
        }

        return sb.ToString();
    }

    private static double MacroF1(IReadOnlyList<HeldOutPrediction> rows)
    {
        var f1 = new List<double>();
        foreach (var intent in rows.Select(r => r.Intent).Distinct(StringComparer.Ordinal))
        {
            var tp = rows.Count(r => r.Intent == intent && r.Predicted == intent);
            var fp = rows.Count(r => r.Intent != intent && r.Predicted == intent);
            var fn = rows.Count(r => r.Intent == intent && r.Predicted != intent);
            f1.Add(2.0 * tp / ((2 * tp) + fp + fn));
        }

        return f1.Average();
    }
}
