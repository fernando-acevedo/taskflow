namespace TaskFlow.Domain.Activity;

/// <summary>What happened. The name is the contract with the frontend, which builds the sentence from it.</summary>
public enum ActivityType
{
    TaskCreated,
    TaskUpdated,
    TaskAssigned,
    TaskMoved,
    TaskDeleted,
    CommentAdded,
    CommentDeleted,
    MemberAdded,
    MemberRemoved,
    MemberRoleChanged,
    LabelCreated,
    LabelRenamed,
    LabelDeleted,
}

/// <summary>
/// One line of a project's history. <see cref="TaskItemId"/> has no foreign key so that the entries of a deleted
/// task stay; <see cref="Changes"/> carries the values the text needs (task title, old and new status, label
/// name...) because the things they name may be renamed or gone by the time someone reads the entry.
/// </summary>
public sealed class ActivityEntry
{
    private ActivityEntry(
        Guid id,
        Guid projectId,
        Guid? taskItemId,
        Guid actorId,
        ActivityType type,
        string changes,
        DateTimeOffset occurredAt)
    {
        Id = id;
        ProjectId = projectId;
        TaskItemId = taskItemId;
        ActorId = actorId;
        Type = type;
        Changes = changes;
        OccurredAt = occurredAt;
    }

    public Guid Id { get; private set; }

    /// <summary>
    /// Generated by the database in insert order, so that entries saved together (an edit and the reassignment in
    /// it) keep the order they were added in. The feeds sort by it after <see cref="OccurredAt"/>.
    /// </summary>
    public long Sequence { get; private set; }

    public Guid ProjectId { get; private set; }

    public Guid? TaskItemId { get; private set; }

    public Guid ActorId { get; private set; }

    public ActivityType Type { get; private set; }

    /// <summary>A JSON object whose keys depend on <see cref="Type"/>.</summary>
    public string Changes { get; private set; }

    public DateTimeOffset OccurredAt { get; private set; }

    /// <param name="id">A version 7 Guid; callers recording several entries at once must pass increasing ids.</param>
    public static ActivityEntry Create(
        Guid id,
        Guid projectId,
        Guid? taskItemId,
        Guid actorId,
        ActivityType type,
        string changesJson,
        DateTimeOffset now) =>
        new(id, projectId, taskItemId, actorId, type, changesJson, now);
}
