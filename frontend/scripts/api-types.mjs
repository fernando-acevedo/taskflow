// Generates src/app/core/api/schema.d.ts from the backend's versioned OpenAPI contract.
// `--check` regenerates in memory and fails when the committed file differs (used in CI).
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, '../docs/api/openapi-1.0.json');
const target = resolve(root, 'src/app/core/api/schema.d.ts');

const header = '// Generated by `npm run api:types` from docs/api/openapi-1.0.json. Do not edit.\n';
const ast = await openapiTS(pathToFileURL(source), { alphabetize: true });
// LF always, so the check passes the same on Windows and Linux.
const generated = (header + astToString(ast)).replace(/\r\n/g, '\n');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
  if (current !== generated) {
    console.error('src/app/core/api/schema.d.ts is out of date. Run `npm run api:types` and commit the result.');
    process.exit(1);
  }
  console.log('API types are up to date.');
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, generated);
  console.log('Wrote src/app/core/api/schema.d.ts');
}
