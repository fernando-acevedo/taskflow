// Serves the frontend for the E2E tests: `ng serve --configuration e2e`, with apiUrl taken from API_URL.
// Angular bakes apiUrl in at build time, so this writes the (git-ignored) src/environments/environment.e2e.ts first.
// Env: API_URL (default http://localhost:5090), BASE_URL (default http://localhost:4200; only its port is used).
import { spawn } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const apiUrl = (process.env.API_URL ?? 'http://localhost:5090').replace(/\/+$/, '');
const port = new URL(process.env.BASE_URL ?? 'http://localhost:4200').port || '4200';

writeFileSync(
  resolve(root, 'src/environments/environment.e2e.ts'),
  `// Generated by scripts/e2e-serve.mjs; do not edit or commit.
export const environment = {
  production: false,
  apiUrl: ${JSON.stringify(apiUrl)},
  appInsightsConnectionString: '',
};
`,
);

const ng = resolve(root, 'node_modules/@angular/cli/bin/ng.js');
const child = spawn(process.execPath, [ng, 'serve', '--configuration', 'e2e', '--port', port, '--host', 'localhost'], {
  cwd: root,
  stdio: 'inherit',
});
child.on('exit', (code) => process.exit(code ?? 0));
for (const signal of ['SIGINT', 'SIGTERM']) {
  process.on(signal, () => child.kill(signal));
}
